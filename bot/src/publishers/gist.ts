/**
 * GitHub Gist Publisher
 * Creates gists to host prompt diffs
 */

interface GistFile {
  content: string;
}

interface CreateGistRequest {
  description: string;
  public: boolean;
  files: Record<string, GistFile>;
}

interface GistResponse {
  id: string;
  html_url: string;
  files: Record<string, { raw_url: string }>;
}

const GIST_API = 'https://api.github.com/gists';

/**
 * Create a new GitHub Gist
 */
export async function createGist(
  filename: string,
  content: string,
  description: string
): Promise<GistResponse> {
  const token = process.env.GITHUB_TOKEN;
  if (!token) {
    throw new Error('GITHUB_TOKEN required to create gists');
  }

  const request: CreateGistRequest = {
    description,
    public: true,
    files: {
      [filename]: { content },
    },
  };

  const response = await fetch(GIST_API, {
    method: 'POST',
    headers: {
      'Accept': 'application/vnd.github.v3+json',
      'Authorization': `Bearer ${token}`,
      'User-Agent': 'clawd-bot/1.0',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(request),
  });

  if (!response.ok) {
    const error = await response.text();
    throw new Error(`Failed to create gist: ${response.status} - ${error}`);
  }

  return await response.json();
}

/**
 * Create a prompt diff gist
 */
export async function createPromptDiffGist(
  oldVersion: string,
  newVersion: string,
  diff: string
): Promise<string> {
  const filename = `claude-code-prompt-diff-${oldVersion}-${newVersion}.md`;

  const content = `# Claude Code Prompt Diff

**From:** ${oldVersion}
**To:** ${newVersion}
**Generated:** ${new Date().toISOString()}

---

## Changes

\`\`\`diff
${diff}
\`\`\`

---

*Generated by [clawd.gg](https://clawd.gg) bot*
`;

  const gist = await createGist(
    filename,
    content,
    `Claude Code prompt diff: ${oldVersion} → ${newVersion}`
  );

  return gist.html_url;
}

/**
 * Mock gist creation for dry run
 */
export function mockCreateGist(
  oldVersion: string,
  newVersion: string,
  diff: string
): string {
  console.log('\n--- MOCK GIST ---');
  console.log(`Diff: ${oldVersion} → ${newVersion}`);
  console.log(`Content length: ${diff.length} chars`);
  console.log('--- END GIST ---\n');

  return `https://gist.github.com/mock/${oldVersion}-${newVersion}`;
}
